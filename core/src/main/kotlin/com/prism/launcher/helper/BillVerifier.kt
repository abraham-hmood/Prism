package com.prism.launcher.helper

import com.prism.core.PrismPlatform
import com.prism.launcher.messaging.PrismText
import java.io.ByteArrayOutputStream
import java.io.File
import java.math.BigDecimal
import java.util.concurrent.Callable
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import java.util.zip.Inflater

/** What a bill appears to say, once it has been read. */
data class BillFacts(
    val biller: String,
    val amountText: String,
    val currency: String,
    val dueLabel: String,
    val reference: String,
    /** The whole bill in USDC micro-units. */
    val usdcMicros: Long,
    /** What the currency conversion assumed, when it had to assume anything. */
    val conversionNote: String,
)

/**
 * The verdict on an uploaded bill.
 *
 * [accepted] is what gates posting. [confidence] is for the person who uploaded it -- "0%" is a
 * different message from "what we read does not look like a bill", and only one of them tells them to
 * pick a different file.
 */
data class BillVerdict(
    val accepted: Boolean,
    val confidence: Int,
    val headline: String,
    val reasons: List<String>,
    val facts: BillFacts?,
    val textChars: Int,
    val usedModel: Boolean,
)

/**
 * Decides whether an uploaded PDF is a real bill.
 *
 * ## Two checks, and why both are needed
 *
 * THE LAYOUT CHECK answers a question a model is bad at: what kind of document IS this. A bill a
 * utility produced has a text layer, embedded fonts, an amount tied to a label, a due date and an
 * account reference. A picture that a generative model drew and somebody printed into a PDF has a
 * single raster image, no fonts and no text at all. Those are not judgements about meaning, they are
 * facts about the file, and they are cheap and exact.
 *
 * THE MODEL CHECK answers the question the layout check cannot: does the prose read like a biller
 * wrote it, or like a model wrote it. It is asked only when a text model is active, its answer is
 * advisory rather than decisive, and a refusal to answer is not a rejection -- a phone with no model
 * loaded still has a working layout check, and requiring a multi-gigabyte download before somebody in
 * trouble can ask for help would be a gate that excludes exactly the people the feature is for.
 *
 * ## What this does NOT claim
 *
 * It cannot detect a bill printed with a forgery tool that reproduces a real biller's layout, and it
 * does not pretend to. What it stops is the common case the feature would otherwise drown in: a
 * screenshot of an AI-drawn invoice, and a PDF generated by a "fake bill" website. The layer that
 * actually protects the pool is the one in the payout flow -- money goes to the author's own address
 * and the total is capped by the requested percentage -- plus the store's refusal to count
 * contributions twice.
 */
object BillVerifier {

    private const val MAX_BYTES = 12L * 1024 * 1024
    private const val MODEL_TIMEOUT_SECONDS = 25L

    /** The amount labels a bill uses, in the order they appear on one. */
    private val AMOUNT_LABELLED = Regex(
        "(?i)(total\\s*due|amount\\s*due|balance\\s*due|amount\\s*payable|amount\\s*owed|total)" +
            "[^0-9]{0,32}([$€£]?)\\s*(\\d{1,3}(?:[,\\s]\\d{3})*[.,]\\d{2}|\\d+[.,]\\d{2})"
    )

    /** Any currency-marked figure, used when no label was found. The largest one wins. */
    private val AMOUNT_MARKED = Regex("([$€£])\\s*(\\d{1,3}(?:[,\\s]\\d{3})*[.,]\\d{2}|\\d+[.,]\\d{2})")

    private val DUE_DATE = Regex(
        "(?i)(due\\s*date|payment\\s*due|due\\s*by|pay\\s*by)" +
            "[^0-9a-z]{0,24}(\\d{1,2}[./-]\\d{1,2}[./-]\\d{2,4}|\\d{4}-\\d{2}-\\d{2}|" +
            "[A-Z][a-z]{2,8}\\s+\\d{1,2},?\\s+\\d{4})"
    )

    private val REFERENCE = Regex(
        "(?i)(account|invoice|bill|customer|reference|acct|policy|meter)\\s*" +
            "(?:no\\.?|number|#|id)?\\s*[:#]?\\s*([A-Z0-9][A-Z0-9/\\-]{3,})"
    )

    /** Tools that generated the file rather than billed for anything. */
    private val AI_TOOLS = listOf(
        "chatgpt", "openai", "gpt-3", "gpt-4", "dall-e", "dall·e", "midjourney",
        "stable diffusion", "stablediffusion", "leonardo.ai", "ideogram", "runway",
        "gemini", "copilot", "claude", "invideo", "sora", "flux.1", "firefly",
    )

    /** Sites whose whole purpose is a bill that does not exist. */
    private val BILL_GENERATORS = listOf(
        "invoice-generator", "invoicegenerator", "fake bill", "bill generator",
        "billgenerator", "bill-generator", "online-bill", "receipt-maker", "receiptmaker",
        "fakebill", "utility-bill-generator",
    )

    fun inspect(file: File): BillVerdict {
        if (!file.isFile) return reject("That file could not be opened.")
        if (file.length() <= 0L) return reject("That file is empty.")
        if (file.length() > MAX_BYTES) return reject("That PDF is larger than 12 MB.")

        val bytes = runCatching { file.readBytes() }.getOrNull()
            ?: return reject("That file could not be read.")
        if (bytes.size < 40) return reject("That file is not a PDF.")
        val header = String(bytes, 0, minOf(5, bytes.size), Charsets.ISO_8859_1)
        if (!header.startsWith("%PDF")) return reject("Only a PDF of a bill can be checked.")

        val raw = String(bytes, Charsets.ISO_8859_1)
        val text = extractText(bytes, raw)
        val compact = text.replace(Regex("\\s+"), " ").trim()
        val producer = meta(raw, "Producer")
        val creator = meta(raw, "Creator")
        val xmp = xmpTool(raw)
        val metadata = listOf(producer, creator, xmp).filter { it.isNotBlank() }.joinToString(" · ")
        val fonts = Regex("/Font\\b").findAll(raw).count()
        val images = Regex("/Subtype\\s*/Image").findAll(raw).count()

        val reasons = ArrayList<String>()
        var score = 0

        when {
            compact.length >= 120 -> {
                score += 35
                reasons += "Readable text layer (${compact.length} characters)."
            }

            compact.length >= 40 -> {
                score += 10
                reasons += "Only a little text could be read (${compact.length} characters)."
            }

            else -> {
                score -= 25
                reasons += "No readable text — a bill is text a billing system printed."
            }
        }

        if (fonts > 0) score += 10 else {
            score -= 15
            reasons += "No embedded fonts, which a generated image saved as a PDF would also lack."
        }

        if (images > 0 && compact.length < 80) {
            score -= 30
            reasons += "The page is an image with no text over it."
        }

        val amount = readAmount(text, raw)
        if (amount != null) {
            score += 20
            reasons += "An amount is stated: ${amount.second}."
        } else {
            reasons += "No amount could be read from the bill."
        }

        val due = DUE_DATE.find(compact)?.groupValues?.getOrNull(2)
        if (due != null) {
            score += 10
            reasons += "A due date is stated: $due."
        }

        val reference = REFERENCE.find(compact)?.groupValues?.getOrNull(2)
        if (reference != null) {
            score += 10
            reasons += "An account or invoice reference is present: $reference."
        }

        val metadataLower = metadata.lowercase()
        val namedAi = AI_TOOLS.firstOrNull { metadataLower.contains(it) }
        val namedGenerator = BILL_GENERATORS.firstOrNull { metadataLower.contains(it) }
        if (namedAi != null) {
            score -= 45
            reasons += "The document's own metadata names a generative tool ($namedAi)."
        }
        if (namedGenerator != null) {
            score -= 45
            reasons += "The document's own metadata names a bill generator ($namedGenerator)."
        }
        if (metadata.isNotBlank()) reasons += "Document tool: $metadata."

        // The model is asked only once the layout facts exist, and only when one can answer.
        val model = askModel(compact, metadata, amount?.second ?: "")
        if (model != null) {
            when {
                model.suspicious && model.confidence >= 60 -> {
                    score -= 40
                    reasons += "The text model reads this as generated (${model.confidence}%): ${model.reason}"
                }

                !model.suspicious && model.confidence >= 60 -> {
                    score += 15
                    reasons += "The text model reads this as a real bill (${model.confidence}%): ${model.reason}"
                }

                else -> reasons += "The text model was not confident either way (${model.confidence}%)."
            }
        } else {
            reasons += if (PrismText.available()) {
                "The text model did not answer in time, so the document checks carried this verdict."
            } else {
                "No text model is active, so the document checks carried this verdict."
            }
        }

        val confidence = (score + 20).coerceIn(0, 99)
        if (amount == null) {
            return BillVerdict(
                accepted = false,
                confidence = confidence,
                headline = "That PDF does not look like a bill we can post",
                reasons = reasons,
                facts = null,
                textChars = compact.length,
                usedModel = model != null,
            )
        }

        val accepted = score >= 55
        val facts = buildFacts(compact, amount, due, reference)
        return BillVerdict(
            accepted = accepted,
            confidence = confidence,
            headline = if (accepted) {
                "Checked — this does not look generated"
            } else {
                "That PDF does not look like a bill we can post"
            },
            reasons = reasons,
            facts = facts,
            textChars = compact.length,
            usedModel = model != null,
        )
    }

    private fun reject(headline: String): BillVerdict =
        BillVerdict(false, 0, headline, listOf(headline), null, 0, false)

    // ── The document ───────────────────────────────────────────────────────

    /**
     * Text out of a PDF's content streams.
     *
     * Most billing systems write their PDFs with Flate-compressed content streams, so the text is not
     * in the file until those are inflated. This walks every `stream … endstream` pair, inflates what
     * it can, and collects the literal strings that the text operators carry. It is not a PDF parser
     * and does not try to be: a CID font with a custom encoding produces garbage, and the checks above
     * treat garbage as "a little text" rather than as a bill, which is the right answer for a file this
     * code cannot read.
     */
    private fun extractText(bytes: ByteArray, raw: String): String {
        val out = StringBuilder()
        collectStrings(raw, out)
        var index = 0
        while (true) {
            val start = raw.indexOf("stream", index)
            if (start < 0) break
            var from = start + 6
            if (from < raw.length && raw[from] == '\r') from++
            if (from < raw.length && raw[from] == '\n') from++
            val end = raw.indexOf("endstream", from)
            if (end < 0) break
            index = end + 9
            if (from >= end || end > bytes.size) continue
            val inflated = inflate(bytes.copyOfRange(from, end)) ?: continue
            collectStrings(String(inflated, Charsets.ISO_8859_1), out)
            out.append(' ')
        }
        return out.toString()
    }

    private fun inflate(input: ByteArray): ByteArray? = runCatching {
        val inflater = Inflater()
        inflater.setInput(input)
        val output = ByteArrayOutputStream(input.size.coerceAtLeast(64) * 4)
        val buffer = ByteArray(16 * 1024)
        while (!inflater.finished()) {
            val read = inflater.inflate(buffer)
            if (read == 0) {
                if (inflater.needsInput() || inflater.needsDictionary()) break
            } else {
                output.write(buffer, 0, read)
            }
        }
        inflater.end()
        output.toByteArray()
    }.getOrNull()

    /** Every parenthesised string in a content stream, unescaped. */
    private fun collectStrings(source: String, out: StringBuilder) {
        var index = 0
        while (index < source.length) {
            val open = source.indexOf('(', index)
            if (open < 0) return
            var cursor = open + 1
            var depth = 1
            val current = StringBuilder()
            while (cursor < source.length && depth > 0) {
                val character = source[cursor]
                when {
                    character == '\\' && cursor + 1 < source.length -> {
                        val escaped = source[cursor + 1]
                        when (escaped) {
                            'n' -> current.append(' ')
                            'r' -> current.append(' ')
                            't' -> current.append(' ')
                            '(', ')', '\\' -> current.append(escaped)
                            else -> if (escaped.isDigit()) {
                                // Three-digit octal escape, e.g. \050 for '('.
                                val digits = source.substring(cursor + 1, minOf(cursor + 4, source.length))
                                    .takeWhile { it.isDigit() }
                                current.append(digits.toIntOrNull(8)?.toChar() ?: ' ')
                                cursor += digits.length - 1
                            }
                        }
                        cursor += 2
                    }

                    character == '(' -> {
                        depth++
                        current.append(character)
                        cursor++
                    }

                    character == ')' -> {
                        depth--
                        if (depth > 0) current.append(character)
                        cursor++
                    }

                    else -> {
                        current.append(character)
                        cursor++
                    }
                }
            }
            if (current.length > 1) out.append(current).append(' ')
            index = cursor.coerceAtLeast(open + 1)
        }
    }

    private fun meta(raw: String, key: String): String {
        val match = Regex("/$key\\s*\\(((?:\\\\.|[^\\\\)])*)\\)").find(raw) ?: return ""
        return match.groupValues[1]
            .replace("\\(", "(")
            .replace("\\)", ")")
            .replace("\\\\", "\\")
            .trim()
            .take(120)
    }

    private fun xmpTool(raw: String): String =
        Regex("<xmp:CreatorTool>([^<]{0,120})</xmp:CreatorTool>").find(raw)
            ?.groupValues?.getOrNull(1)?.trim().orEmpty()

    // ── What it says ───────────────────────────────────────────────────────

    private fun readAmount(text: String, raw: String): Triple<String, String, String>? {
        val source = text.ifBlank { raw }
        val labelled = AMOUNT_LABELLED.find(source)
        if (labelled != null) {
            val symbol = labelled.groupValues[2]
            val figure = labelled.groupValues[3]
            if (parseFigure(figure) != null) {
                return Triple(symbol, figure, currencyOf(symbol))
            }
        }
        val marked = AMOUNT_MARKED.findAll(source)
            .mapNotNull { match ->
                val figure = match.groupValues[2]
                val value = parseFigure(figure) ?: return@mapNotNull null
                Triple(match.groupValues[1], figure, currencyOf(match.groupValues[1])) to value
            }
            .sortedByDescending { it.second }
            .firstOrNull()
            ?: return null
        return marked.first
    }

    private fun parseFigure(figure: String): BigDecimal? = runCatching {
        val cleaned = figure.replace(" ", "").replace(",", "")
        if (cleaned.count { it == '.' } > 1 || cleaned.isBlank()) return null
        cleaned.toBigDecimalOrNull()?.takeIf { it.signum() > 0 }
    }.getOrNull()

    private fun currencyOf(symbol: String): String = when (symbol) {
        "€" -> "EUR"
        "£" -> "GBP"
        else -> "USD"
    }

    private fun buildFacts(
        compact: String,
        amount: Triple<String, String, String>,
        due: String?,
        reference: String?,
    ): BillFacts {
        val value = parseFigure(amount.second) ?: BigDecimal.ZERO
        val conversion = HelpMoney.toUsdc(value, amount.third)
        val biller = compact.split(". ")
            .firstOrNull { line -> line.count { it.isLetter() } >= 3 && line.length in 3..60 }
            ?.trim()
            .orEmpty()
        return BillFacts(
            biller = biller.ifBlank { "the biller" },
            amountText = "${amount.first}${amount.second} ${amount.third}".trim(),
            currency = amount.third,
            dueLabel = due.orEmpty(),
            reference = reference.orEmpty(),
            usdcMicros = conversion.micros,
            conversionNote = conversion.note,
        )
    }

    // ── The model ──────────────────────────────────────────────────────────

    private data class ModelReading(
        val suspicious: Boolean,
        val confidence: Int,
        val reason: String,
    )

    private fun askModel(text: String, metadata: String, amount: String): ModelReading? {
        if (!PrismText.available()) return null
        val excerpt = text.take(1800)
        if (excerpt.length < 40) return null
        val system =
            "You examine documents for signs that a bill was written or drawn by a generative AI " +
                "tool rather than issued by a real biller. Judge only the text: a real bill is terse, " +
                "has line items, an account number, a total and a due date; generated text tends to " +
                "read like prose, repeats itself, or describes the bill instead of charging for " +
                "anything. Reply with exactly three lines:\n" +
                "VERDICT: REAL or GENERATED\nCONFIDENCE: 0-100\nREASON: one short sentence"
        val user = buildString {
            if (metadata.isNotBlank()) append("Document metadata: ").append(metadata).append("\n")
            if (amount.isNotBlank()) append("Stated amount: ").append(amount).append("\n")
            append("Bill text:\n").append(excerpt)
        }
        val reply = withTimeout {
            PrismText.complete(system, user, maxTokens = 160, temperature = 0.1f)
        } ?: return null

        val upper = reply.uppercase()
        val verdictLine = reply.lineSequence().firstOrNull { it.uppercase().contains("VERDICT") }
            ?: return null
        val generated = verdictLine.uppercase().contains("GENERATED") ||
            (verdictLine.uppercase().contains("FAKE"))
        if (!generated && !verdictLine.uppercase().contains("REAL")) {
            // A reply that names neither is not a judgement, and treating it as one would let a
            // rambling model reject an honest bill.
            if (!upper.contains("REAL")) return null
        }
        val confidence = Regex("(?i)confidence\\s*[:\\-]?\\s*(\\d{1,3})").find(reply)
            ?.groupValues?.getOrNull(1)?.toIntOrNull()?.coerceIn(0, 100) ?: 50
        val reason = Regex("(?i)reason\\s*[:\\-]\\s*(.+)").find(reply)
            ?.groupValues?.getOrNull(1)?.trim()?.take(160)
            ?: reply.lineSequence().lastOrNull()?.trim()?.take(160).orEmpty()
        return ModelReading(generated, confidence, reason)
    }

    /**
     * A model call with a ceiling.
     *
     * `PrismText.complete` can block for as long as the engine takes, and this runs while somebody is
     * standing there holding a phone with their bill on it. A slow model must not turn into a hang:
     * past the deadline the layout checks stand on their own and the verdict says so.
     */
    private fun withTimeout(block: () -> String?): String? {
        val executor = Executors.newSingleThreadExecutor { runnable ->
            Thread(runnable, "helper-bill-model").apply { isDaemon = true }
        }
        return try {
            val future = executor.submit(Callable { block() })
            future.get(MODEL_TIMEOUT_SECONDS, TimeUnit.SECONDS)
        } catch (ex: Exception) {
            PrismPlatform.log.warn("PrismHelper", "Bill model did not answer: ${ex.message}")
            null
        } finally {
            executor.shutdownNow()
        }
    }
}
