 * missing concept. The parser is in [Lexicon], and [LexiconCoverageTest] fails the build if an id
 * here does not exist in [Concepts] — which is the only real risk of a loose format like this.
 *
 * ## What is and is not here
 *
 * The citation form, because that is what a learner is taught first and what the tutor introduces.
