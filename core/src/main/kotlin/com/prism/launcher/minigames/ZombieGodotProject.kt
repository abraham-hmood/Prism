func _process(delta: float) -> void:
    if status != 0:
        _update_hud(delta)
        return
    if between_waves:
        wave_timer -= delta
        if wave_timer <= 0.0:
            _start_wave(false)
    else:
        if to_spawn > 0 and zombies.size() < MAX_ZOMBIES:
            spawn_clock -= delta
            if spawn_clock <= 0.0:
                _spawn_zombie()
                to_spawn -= 1
                spawn_clock = maxf(0.25, 1.05 - wave * 0.045)
        if remaining <= 0 and to_spawn <= 0:
            between_waves = true
            wave_timer = 8.0
