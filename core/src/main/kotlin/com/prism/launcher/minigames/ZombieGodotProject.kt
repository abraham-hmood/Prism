func _build_world() -> void:
    var wall_material = _material("wall_concrete", 1.0, Color(0.82, 0.80, 0.78))
    var floor_material = _material("floor_tile", 1.0, Color(0.75, 0.73, 0.70))
    var ceiling_material = _material("wall_concrete", 1.0, Color(0.32, 0.30, 0.38))
    var metal_material = _material("metal_plate", 1.0, Color(0.58, 0.60, 0.66))
    var dark_metal = _material("metal_plate", 0.7, Color(0.20, 0.21, 0.26))

    var floor = MeshBuilder.new()
    var ceiling = MeshBuilder.new()
    var walls = MeshBuilder.new()
    var trim = MeshBuilder.new()
    var metal = MeshBuilder.new()

    for y in range(height):
        var line: String = str(rows[y])
        for x in range(width):
            var ch = line[x]
            if ch == "#":
                wall_cells[Vector2i(x, y)] = true
                continue
            floor_cells.append(Vector2i(x, y))
            var u0 = Vector2(x * 0.5, y * 0.5)
            var u1 = Vector2((x + 1) * 0.5, (y + 1) * 0.5)
            floor.quad(
                Vector3(x, 0, y), Vector3(x, 0, y + 1), Vector3(x + 1, 0, y + 1), Vector3(x + 1, 0, y),
                Vector3.UP, u0, Vector2(u0.x, u1.y), u1, Vector2(u1.x, u0.y)
            )
            ceiling.quad(
                Vector3(x, WALL_HEIGHT, y), Vector3(x + 1, WALL_HEIGHT, y), Vector3(x + 1, WALL_HEIGHT, y + 1), Vector3(x, WALL_HEIGHT, y + 1),
                Vector3.DOWN,
                Vector2(x * 0.22, y * 0.22), Vector2((x + 1) * 0.22, y * 0.22),
                Vector2((x + 1) * 0.22, (y + 1) * 0.22), Vector2(x * 0.22, (y + 1) * 0.22)
            )
            # Wall faces are added once per exposed side. The UVs are world-scaled so a long hall
            # does not stretch one 1024 texture across forty metres.
            _wall_face(walls, trim, metal, x, y, 0, -1)
            _wall_face(walls, trim, metal, x, y, 0, 1)
            _wall_face(walls, trim, metal, x, y, -1, 0)
            _wall_face(walls, trim, metal, x, y, 1, 0)

    var floor_node = MeshInstance3D.new()
    floor_node.mesh = floor.build(floor_material)
    add_child(floor_node)
    var ceiling_node = MeshInstance3D.new()
    ceiling_node.mesh = ceiling.build(ceiling_material)
    add_child(ceiling_node)
    var wall_node = MeshInstance3D.new()
    wall_node.mesh = walls.build(wall_material)
    add_child(wall_node)
    var trim_node = MeshInstance3D.new()
    trim_node.mesh = trim.build(metal_material)
    add_child(trim_node)
    var metal_node = MeshInstance3D.new()
    metal_node.mesh = metal.build(dark_metal)
    add_child(metal_node)

    _build_collision()
    _build_ceiling_beams(metal_material)
    _build_props(metal_material)
    _build_lamps()

func _wall_face(walls: MeshBuilder, trim: MeshBuilder, metal: MeshBuilder, x: int, y: int, dx: int, dy: int) -> void:
    var nx = x + dx
    var ny = y + dy
    if nx < 0 or ny < 0 or nx >= width or ny >= height:
        return
    var line: String = str(rows[ny])
    if line[nx] == "#":
        return
    var normal := Vector3(dx, 0, dy)
    var a: Vector3
    var b: Vector3
    var c: Vector3
    var d: Vector3
    var ua: Vector2
    var ub: Vector2
    var uc: Vector2
    var ud: Vector2
    if dx == 1:
        a = Vector3(x + 1, 0, y)
        b = Vector3(x + 1, 0, y + 1)
    elif dx == -1:
        a = Vector3(x, 0, y + 1)
        b = Vector3(x, 0, y)
    elif dy == 1:
        a = Vector3(x + 1, 0, y + 1)
        b = Vector3(x, 0, y + 1)
    else:
        a = Vector3(x, 0, y)
        b = Vector3(x + 1, 0, y)
    c = b + Vector3(0, WALL_HEIGHT, 0)
    d = a + Vector3(0, WALL_HEIGHT, 0)
    ua = Vector2(a.x + a.z, 0)
    ub = Vector2(b.x + b.z, 0)
    uc = Vector2(b.x + b.z, 3.2)
    ud = Vector2(a.x + a.z, 3.2)
    walls.quad(a, b, c, d, normal, ua, ub, uc, ud)

    # Skirting and a high rail. These are thin quads offset into the walkable cell, so they read as
    # architecture instead of z-fighting with the wall texture.
    var inset = normal * 0.012
    var lo0 = a + inset + Vector3(0, 0.02, 0)
    var lo1 = b + inset + Vector3(0, 0.02, 0)
    var lo2 = b + inset + Vector3(0, 0.24, 0)
    var lo3 = a + inset + Vector3(0, 0.24, 0)
    trim.quad(lo0, lo1, lo2, lo3, normal, Vector2(0, 0), Vector2(1, 0), Vector2(1, 0.1), Vector2(0, 0.1))
    var hi0 = a + inset + Vector3(0, 2.78, 0)
    var hi1 = b + inset + Vector3(0, 2.78, 0)
    var hi2 = b + inset + Vector3(0, 2.96, 0)
    var hi3 = a + inset + Vector3(0, 2.96, 0)
    trim.quad(hi0, hi1, hi2, hi3, normal, Vector2(0, 0), Vector2(1, 0), Vector2(1, 0.1), Vector2(0, 0.1))

    # One panel rib every few metres, with a rivet line. Cheap geometry, strong silhouettes.
    if (x * 3 + y * 7 + dx + dy) % 9 == 0:
        var rib0 = a + inset + Vector3(0, 0.20, 0)
        var rib1 = b.lerp(a, 0.86) + inset + Vector3(0, 0.20, 0)
        var rib2 = b.lerp(a, 0.86) + inset + Vector3(0, 2.86, 0)
        var rib3 = a + inset + Vector3(0, 2.86, 0)
        metal.quad(rib0, rib1, rib2, rib3, normal, Vector2(0, 0), Vector2(1, 0), Vector2(1, 1), Vector2(0, 1))

func _build_collision() -> void:
    var body := StaticBody3D.new()
    add_child(body)
    var floor_shape := CollisionShape3D.new()
    var floor_box := BoxShape3D.new()
    floor_box.size = Vector3(width, 0.2, height)
    floor_shape.shape = floor_box
    floor_shape.position = Vector3(width * 0.5, -0.1, height * 0.5)
    body.add_child(floor_shape)
    var wall_shape := BoxShape3D.new()
    wall_shape.size = Vector3(1, WALL_HEIGHT, 1)
    for cell in wall_cells.keys():
        var shape := CollisionShape3D.new()
        shape.shape = wall_shape
        shape.position = Vector3(cell.x + 0.5, WALL_HEIGHT * 0.5, cell.y + 0.5)
        body.add_child(shape)

func _build_ceiling_beams(material: Material) -> void:
    for y in range(3, height, 6):
        var beam = MeshInstance3D.new()
        var mesh := BoxMesh.new()
        mesh.size = Vector3(width, 0.12, 0.24)
        beam.mesh = mesh
        beam.position = Vector3(width * 0.5, WALL_HEIGHT - 0.12, y + 0.5)
