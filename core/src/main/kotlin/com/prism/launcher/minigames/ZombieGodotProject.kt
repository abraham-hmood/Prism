import java.io.File

/**
 * Writes the playable Godot 4 export of Zombies.
 *
 * ## Why the project is generated instead of checked in
 *
 * Its map, meshes and textures are seeded, not hand-authored. Writing the project next to them
 * means a custom baseline folder can replace any single asset without a second copy of the game
 * logic, and the export always describes the same run the launcher just generated.
 *
 * ## What is actually authored here
 *
 * The scripts build the level from the layout JSON at load time: merged floor/ceiling surfaces,
 * wall panels, trim, pillars, ceiling beams, lamps, crates and barrels, a real navigation grid, and
 * a rig whose arms and legs are separate meshes. The result is deliberately a wave-survival game in
 * the spirit of the mode, not a copy of a Treyarch map, weapon or character.
 */
object ZombieGodotProject {

    fun write(
        godot: File,
        layout: File,
        sounds: Map<MinigameSfx.Sound, File>,
        music: Map<String, File>,
        parts: ZombieKit.ZombieParts,
    ) {
        val scenes = File(godot, "scenes").apply { mkdirs() }
        val scripts = File(godot, "scripts").apply { mkdirs() }
        val blender = File(godot, "blender").apply { mkdirs() }
        File(godot, "icon.svg").writeText(ICON, Charsets.UTF_8)
        File(godot, "project.godot").writeText(PROJECT, Charsets.UTF_8)
        File(scenes, "main.tscn").writeText(MAIN_SCENE, Charsets.UTF_8)
        File(scenes, "player.tscn").writeText(PLAYER_SCENE, Charsets.UTF_8)
        File(scenes, "zombie.tscn").writeText(ZOMBIE_SCENE, Charsets.UTF_8)
        File(scripts, "game.gd").writeText(GAME, Charsets.UTF_8)
        File(scripts, "player.gd").writeText(PLAYER, Charsets.UTF_8)
        File(scripts, "zombie.gd").writeText(ZOMBIE, Charsets.UTF_8)
        File(blender, "build_assets.py").writeText(BLENDER, Charsets.UTF_8)
        File(godot, "export_presets.cfg").writeText(EXPORT, Charsets.UTF_8)
        File(godot, "README.md").writeText(README, Charsets.UTF_8)
        // A marker for a future "open this folder" action; the path is the only thing it needs.
        File(godot, "LAYOUT.txt").writeText(layout.absolutePath + "\n", Charsets.UTF_8)
    }

