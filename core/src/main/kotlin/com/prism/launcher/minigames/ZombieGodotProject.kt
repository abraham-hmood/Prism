func _process_projectiles(delta: float) -> void:
    for entry in projectiles.duplicate():
        if not is_instance_valid(entry["node"]):
            projectiles.erase(entry)
            continue
        var node = entry["node"]
        node.position += entry["velocity"] * delta
        entry["life"] -= delta
        if entry["life"] <= 0.0:
            node.queue_free()
            projectiles.erase(entry)
            continue
        for player in players:
            if player.health > 0.0 and not player.downed and node.position.distance_to(player.global_position + Vector3(0, 1.0, 0)) < 0.75:
                player.take_damage(float(entry["damage"]))
                node.queue_free()
                projectiles.erase(entry)
                break

