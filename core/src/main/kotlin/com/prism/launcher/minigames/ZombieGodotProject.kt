func _build_props(material: Material) -> void:
    var used := 0
    for cell in floor_cells:
        if used >= 30:
            break
        if cell.x < 2 or cell.y < 2 or cell.x >= width - 2 or cell.y >= height - 2:
            continue
        if prop_cells.has(cell):
            continue
        if rng.randf() > 0.028:
            continue
        var walls = 0
        for d in [Vector2i(1, 0), Vector2i(-1, 0), Vector2i(0, 1), Vector2i(0, -1)]:
            if wall_cells.has(cell + d):
                walls += 1
        if walls < 1:
            continue
        if used % 3 == 0:
            _add_crate(cell, material)
        else:
            _add_barrel(cell, material)
        prop_cells[cell] = true
        used += 1

