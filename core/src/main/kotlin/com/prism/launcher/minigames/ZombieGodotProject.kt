func nearest_downed(player):
    var best = null
    var best_distance := 3.0
    for other in players:
        if other == player or not other.downed or other.health <= 0.0:
            continue
        var d = player.global_position.distance_to(other.global_position)
        if d < best_distance:
            best_distance = d
            best = other
    return best

func try_interact(player, delta: float) -> void:
    if player.downed or player.health <= 0.0:
        return
    if player.interact_cooldown > 0.0:
        return
    var downed = nearest_downed(player)
    if downed != null:
        downed.revive_progress += delta
        interaction_text = "REVIVING " + downed.player_name + "  " + str(int(downed.revive_progress * 100.0 / 1.8)) + "%"
        interaction_timer = 0.2
        if downed.revive_progress >= 1.8:
            downed.revive()
            points += 75
            _say("ROOK", downed.player_name + " is back. Stay close.")
            interaction_text = ""
        return
    for entry in pickups.duplicate():
        if player.global_position.distance_to(entry["node"].global_position) < 1.8:
            if entry["kind"] == "weapon":
                player.equip(entry["weapon"])
                points += 10
            elif entry["kind"] == "ammo":
                player.reserve = min(player.reserve + 45, player.WEAPONS[player.weapon]["reserve"] * 2)
            elif entry["kind"] == "health":
                player.health = min(player.max_health, player.health + 45.0)
            _say("JINX", "Picked up " + str(entry["label"]) + ".")
            entry["node"].queue_free()
            pickups.erase(entry)
            return
    if player.global_position.distance_to(supply_pos) < 2.5:
        if buy_clock > 0.0:
            return
        if points >= 400:
            points -= 400
            player.reserve = player.WEAPONS[player.weapon]["reserve"] * 2
            _say("ROOK", "Ammo's topped off. Spend the rest on armour.")
        elif points >= 300:
            points -= 300
            player.health = min(player.max_health, player.health + 50.0)
            _say("MARA", "That'll keep you standing.")
        else:
            _say("ROOK", "Not enough points. Kill more, then come back.")
        buy_clock = 0.8
        interaction_text = ""
        return
    interaction_text = ""

func bot_revive(bot, target, delta: float) -> void:
    if target == null or not target.downed or target.health <= 0.0:
        return
    target.revive_progress += delta * 0.85
