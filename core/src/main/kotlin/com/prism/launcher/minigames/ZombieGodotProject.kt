            _give_wave_reward()
            _music_for_wave()
    _process_projectiles(delta)
    for lamp in lamps:
        lamp.light_energy = 0.78 + sin(Time.get_ticks_msec() * 0.0017 + float(lamp.get_meta("phase", 0.0))) * 0.18
    buy_clock = maxf(0.0, buy_clock - delta)
    damage_flash = maxf(0.0, damage_flash - delta * 1.8)
