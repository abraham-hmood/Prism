func path_to(from: Vector3, to: Vector3) -> PackedVector2Array:
    var a := Vector2i(clampi(int(floor(from.x)), 0, width - 1), clampi(int(floor(from.z)), 0, height - 1))
    var b := Vector2i(clampi(int(floor(to.x)), 0, width - 1), clampi(int(floor(to.z)), 0, height - 1))
    if astar == null or astar.is_point_solid(a) or astar.is_point_solid(b):
        return PackedVector2Array()
    var ids = astar.get_id_path(a, b)
    var out := PackedVector2Array()
    for id in ids:
        out.append(Vector2(id.x + 0.5, id.y + 0.5))
    return out

func has_los(from: Vector3, to: Vector3) -> bool:
