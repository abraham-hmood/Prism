package com.prism.core

import com.prism.launcher.AppDatabase
import com.prism.launcher.AppLaunchStatEntity
import com.prism.launcher.InstalledAppEntity
import com.prism.launcher.JvmDatabase
import com.prism.launcher.agentic.AgenticToolEntity
import com.prism.launcher.messaging.AiMessageEntity
import com.prism.launcher.social.SocialBotEntity
import com.prism.launcher.social.SocialCommentEntity
import com.prism.launcher.social.SocialPostEntity
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import java.io.File
import kotlin.test.AfterTest
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * Proves Room actually runs off Android.
 *
 * Compiling is not the interesting part -- KSP will happily generate `_Impl` classes that fail
 * the moment they meet a real SQLite connection. What these tests check is that the bundled
 * driver loads its native library, that the generated SQL executes, and specifically that the
 * queries relying on SQLite dialect quirks still behave: `LIKE '%' || :q || '%'` string
 * concatenation, `GROUP BY` returning a bare non-aggregated column, `COUNT(*)` coerced to a
 * Boolean return type, and `IS NULL` filtering on a nullable self-referencing foreign key.
 *
 * Those are the four places where "Room compiled" and "Room works" could plausibly diverge.
 */
class DatabaseTest {

    private lateinit var dir: File
    private lateinit var db: AppDatabase

    @BeforeTest
    fun open() {
        dir = File(System.getProperty("java.io.tmpdir"), "prism-db-${System.nanoTime()}")
        dir.mkdirs()
        db = JvmDatabase.open(File(dir, "test.db"))
    }

    @AfterTest
    fun close() {
        db.close()
        dir.deleteRecursively()
    }

    /** The most basic claim: a table exists and survives a write. */
    @Test
    fun `installed apps round-trip`() = runTest {
        val dao = db.installedAppDao()
        assertEquals(0, dao.count())

        dao.insertAll(
            listOf(
                InstalledAppEntity("com.b.app", "com.b.app.Main"),
                InstalledAppEntity("com.a.app", "com.a.app.Main"),
            )
        )

        val all = dao.getAll()
        assertEquals(2, all.size)
        // ORDER BY packageName ASC -- a is before b.
        assertEquals("com.a.app", all[0].packageName)

        dao.deleteByPackage("com.a.app")
        assertEquals(1, dao.count())
    }

    /**
     * Room's Flow queries depend on its invalidation tracker, which is a separate mechanism from
     * plain query execution and a plausible thing to be Android-only. The drawer relies on it.
     */
    @Test
    fun `observeAll emits`() = runTest {
        val dao = db.installedAppDao()
        dao.insertAll(listOf(InstalledAppEntity("com.x", "com.x.Main")))
        assertEquals(1, dao.observeAll().first().size)
    }

    /**
     * The launch-statistics path HotseatPredictor depends on: a composite primary key, an
     * insert-or-ignore followed by an UPDATE that must report how many rows it touched.
     */
    @Test
    fun `launch stats increment against a composite key`() = runTest {
        val dao = db.appLaunchStatDao()

        assertEquals(0, dao.increment("com.x/Main", 9), "no row yet, so nothing to update")
        dao.insertOrIgnore(AppLaunchStatEntity("com.x/Main", 9, 1))
        assertEquals(1, dao.increment("com.x/Main", 9), "row exists, so exactly one update")

        assertEquals(2, dao.getStatsForHour(9).single().launchCount)
        // Same component, different hour -- the composite key must keep these separate.
        dao.insertOrIgnore(AppLaunchStatEntity("com.x/Main", 10, 1))
        assertEquals(1, dao.getStatsForHour(10).single().launchCount)

        assertEquals(listOf("com.x/Main"), dao.getTopForHour(9, 4))
        assertEquals(listOf("com.x/Main"), dao.getTopOverall(1))
    }

    /**
     * `SELECT * FROM ai_messages WHERE text LIKE '%' || :query || '%'`.
     *
     * `||` is SQLite's string concatenation; in MySQL it is a boolean OR, which would make this
     * query silently match everything. Worth pinning precisely because the failure is not an error.
     */
    @Test
    fun `message search uses SQLite string concatenation`() = runTest {
        val dao = db.aiMessageDao()
        dao.insert(AiMessageEntity(text = "a note about penguins", isSent = true, timestamp = 1))
        dao.insert(AiMessageEntity(text = "unrelated", isSent = false, timestamp = 2))

        assertEquals(1, dao.searchMessages("penguin").size)
        assertEquals(0, dao.searchMessages("walrus").size)
        assertEquals(2, dao.getAllMessages().first().size)
    }

    /** autoGenerate primary keys must actually generate. */
    @Test
    fun `autogenerated ids are assigned`() = runTest {
        val dao = db.aiMessageDao()
        dao.insert(AiMessageEntity(text = "one", isSent = true, timestamp = 1))
        dao.insert(AiMessageEntity(text = "two", isSent = true, timestamp = 2))
        val ids = dao.getAllMessages().first().map { it.id }
        assertEquals(2, ids.toSet().size, "ids must be distinct")
        assertTrue(ids.all { it > 0 }, "ids must be non-zero: $ids")
    }

    /**
     * Comments form a tree via a nullable self-reference, and top-level comments are selected
     * with `parentCommentId IS NULL`. `= NULL` would return nothing at all in SQL; this pins that
     * the generated query got it right.
     */
    @Test
    fun `comment tree separates roots from replies`() = runTest {
        val dao = db.socialDao()
        dao.insertPost(
            SocialPostEntity(
                postId = "p1", authorId = "b1", authorName = "Bot", authorHandle = "@bot",
                authorAvatarUrl = null, content = "hello", imageUrl = null, timestamp = 1,
            )
        )
        dao.insertComment(
            SocialCommentEntity(
                commentId = "c1", postId = "p1", parentCommentId = null, authorId = "u",
                authorName = "U", authorHandle = "@u", authorAvatarUrl = null,
                content = "root", timestamp = 2,
            )
        )
        dao.insertComment(
            SocialCommentEntity(
                commentId = "c2", postId = "p1", parentCommentId = "c1", authorId = "u",
                authorName = "U", authorHandle = "@u", authorAvatarUrl = null,
                content = "reply", timestamp = 3,
            )
        )

        val roots = dao.getCommentsForPost("p1")
        assertEquals(1, roots.size, "only the top-level comment")
        assertEquals("root", roots.single().content)
        assertEquals("reply", dao.getReplies("c1").single().content)

        assertNotNull(dao.getPostById("p1"))
        assertNull(dao.getPostById("nope"))
    }

    /** `SELECT COUNT(*) ...` returning Boolean -- Room coerces; SQLite must agree. */
    @Test
    fun `follow state is a coerced count`() = runTest {
        val dao = db.socialDao()
        val bot = SocialBotEntity(
            botId = "b1", name = "Bot", handle = "@bot", bio = "", avatarUrl = null,
            personaType = "tech",
        )
        dao.insertBot(bot)
        assertEquals(false, dao.isFollowing("b1"))
        dao.follow(com.prism.launcher.social.SocialFollowEntity(botId = "b1", timestamp = 1))
        assertEquals(true, dao.isFollowing("b1"))
        dao.unfollow("b1")
        assertEquals(false, dao.isFollowing("b1"))
    }

    /** Default column values declared in Kotlin must survive a round trip through SQL. */
    @Test
    fun `agentic tool defaults persist`() = runTest {
        val dao = db.agenticDao()
        dao.upsertTool(
            AgenticToolEntity(id = "t1", name = "weather", description = "d", httpUrl = "http://x")
        )
        val loaded = dao.getAllTools().single()
        assertEquals("GET", loaded.httpMethod)
        assertEquals("{\"type\":\"object\",\"properties\":{}}", loaded.parametersJson)
        assertTrue(loaded.enabled)
        assertEquals(1, dao.getEnabledTools().size)

        dao.deleteTool("t1")
        assertEquals(0, dao.getAllTools().size)
    }

    /**
     * The point of the whole exercise: data written by one process is still there for the next.
     * A driver misconfigured to open in-memory would pass every test above and fail this one.
     */
    @Test
    fun `data survives close and reopen`() = runTest {
        val file = File(dir, "persist.db")
        JvmDatabase.open(file).use { first ->
            first.installedAppDao().insertAll(listOf(InstalledAppEntity("com.p", "com.p.Main")))
        }
        JvmDatabase.open(file).use { second ->
            assertEquals("com.p", second.installedAppDao().getAll().single().packageName)
        }
        assertTrue(file.exists(), "the database must be a real file on disk")
    }

    private inline fun <T : AppDatabase, R> T.use(block: (T) -> R): R =
        try { block(this) } finally { close() }
}
