package com.prism.launcher.wallet

import java.math.BigInteger

/**
 * Generates a whole chain configuration from nothing but a name.
 *
 * ## Everything except the name is derived, and derived DETERMINISTICALLY
 *
 * Genesis parameters, magic bytes, address prefixes, ports and the reward schedule are all
 * functions of the coin's name, hashed. Two consequences, both deliberate:
 *
 *   THE SAME NAME ALWAYS PRODUCES THE SAME CHAIN. Someone else creating "Foocoin" on their device
 *   gets byte-identical parameters, so the two are the same network rather than two chains sharing
 *   a name. That is what makes a user-created coin something more than a private toy.
 *
 *   NOBODY HAS TO UNDERSTAND ANY OF IT. Picking a magic number or a version byte badly produces a
 *   chain that half-works -- addresses that collide with another coin's, ports that clash, a
 *   genesis nobody else can reproduce. Deriving them removes an entire class of mistake from a
 *   screen where the user just wanted to name a coin.
 *
 * ## What this does NOT create
 *
 * A configuration is not a network. There is no node software here, no peers and no ledger --
 * [CustomChain] describes a chain that something else must actually run. Prism gives the resulting
 * coin a wallet and a miner immediately, because those only need parameters; the node has to live
 * on a PC.
 */
data class CustomChain(
    val name: String,
    val symbol: String,
    /** Network identifier prefixing every P2P message; distinguishes chains that share a port. */
    val magicBytes: ByteArray,
    /** Base58 version byte, which fixes the leading character of every address. */
    val addressVersion: Int,
    val p2pPort: Int,
    val rpcPort: Int,
    /** Fixed, so every node computes the same genesis hash. */
    val genesisTimestamp: Long,
    val genesisNonce: Long,
    val genesisMessage: String,
    /** Initial block reward in whole coins. */
    val initialReward: Long,
    /** Blocks between halvings; 0 means a flat reward forever. */
    val halvingInterval: Long,
    val targetBlockSeconds: Int,
    val decimals: Int = 8,
) {
    /** The wallet-side view of this chain, so it lists and derives like any other coin. */
    fun toCoinSpec(coinType: Long): CoinSpec = CoinSpec(
        symbol = symbol,
        name = name,
        coinType = coinType,
        scheme = AddressScheme.P2PKH(addressVersion),
        decimals = decimals,
        isCustom = true,
        supportsPruning = true,
        miningAlgorithm = MiningAlgorithms.SHA256D,
    )

    fun magicHex(): String = WalletCrypto.toHex(magicBytes)

    /** A `coin.conf` a node can be started with. */
    fun toConfig(): String = buildString {
        appendLine("# $name ($symbol) — generated by Prism")
        appendLine("# Every value below is derived from the coin name, so anyone creating")
        appendLine("# \"$name\" gets an identical chain and joins the same network.")
        appendLine("chainname=${symbol.lowercase()}")
        appendLine("magic=${magicHex()}")
        appendLine("addressversion=$addressVersion")
        appendLine("port=$p2pPort")
        appendLine("rpcport=$rpcPort")
        appendLine("genesistime=$genesisTimestamp")
        appendLine("genesisnonce=$genesisNonce")
        appendLine("genesismessage=$genesisMessage")
        appendLine("blockreward=$initialReward")
        appendLine("halvinginterval=$halvingInterval")
        appendLine("targetspacing=$targetBlockSeconds")
    }

    override fun equals(other: Any?): Boolean =
        other is CustomChain && symbol == other.symbol && magicBytes.contentEquals(other.magicBytes)

    override fun hashCode(): Int = symbol.hashCode() * 31 + magicBytes.contentHashCode()
}

object CustomChainFactory {

    /** Ports are drawn from the registered-but-unassigned range to avoid well-known services. */
    private const val PORT_BASE = 20_000
    private const val PORT_SPAN = 20_000

    /**
     * Builds a chain from a name.
     *
     * The name is the only input, and the hash of it seeds everything else. Symbols are derived
     * from the name's letters so that "Foo Coin" gives FOO rather than requiring the user to invent
     * a ticker as well.
     */
    fun create(name: String): CustomChain {
        val clean = name.trim()
        require(clean.isNotBlank()) { "a coin needs a name" }

        val seed = WalletCrypto.sha256(clean.lowercase().toByteArray(Charsets.UTF_8))
        fun slice(offset: Int, length: Int): BigInteger =
            BigInteger(1, seed.copyOfRange(offset, offset + length))

        // Address version is constrained so the leading character lands in a readable range and
        // does not collide with Bitcoin's `1` or `3`.
        val addressVersion = 0x10 + slice(0, 1).toInt() % 0x60

        val p2pPort = PORT_BASE + (slice(1, 2).toInt() % PORT_SPAN)
        // RPC sits directly above P2P, the convention every Bitcoin fork follows.
        val rpcPort = if (p2pPort + 1 > 65_000) p2pPort - 1 else p2pPort + 1

        return CustomChain(
            name = clean,
            symbol = symbolFor(clean),
            magicBytes = seed.copyOfRange(3, 7),
            addressVersion = addressVersion,
            p2pPort = p2pPort,
            rpcPort = rpcPort,
            // Fixed rather than "now": a genesis timestamp taken from the clock would give every
            // device a different genesis block and therefore a different chain.
            genesisTimestamp = 1767225600L,
            genesisNonce = slice(7, 4).toLong() and 0xFFFFFFFFL,
            genesisMessage = "$clean — created with Prism",
            initialReward = 50,
            halvingInterval = 210_000,
            targetBlockSeconds = 120,
        )
    }

    /**
     * A ticker from a name: initials for multi-word names, otherwise the leading consonants.
     *
     * Deterministic, because the symbol is part of the chain's identity -- two people naming the
     * same coin must agree on it without coordinating.
     */
    fun symbolFor(name: String): String {
        val words = name.trim().split(Regex("\\s+")).filter { it.isNotBlank() }
        val letters = if (words.size >= 2) {
            words.joinToString("") { it.first().uppercase() }
        } else {
            val word = words.firstOrNull()?.uppercase() ?: "COIN"
            // Keep the first letter, then drop vowels, which is how most tickers are built.
            (word.take(1) + word.drop(1).filter { it !in "AEIOU" }).ifBlank { word }
        }
        return letters.filter { it.isLetter() }.take(5).ifBlank { "COIN" }
    }

    /**
     * SLIP-44 coin type for a user chain.
     *
     * Taken from the reserved-for-testing range above 0x80000000's practical use, hashed from the
     * name so it is stable. It will not be registered with SLIP-44 and does not need to be -- what
     * matters is that the same coin derives the same keys on every device.
     */
    fun coinTypeFor(name: String): Long {
        val seed = WalletCrypto.sha256(("cointype:" + name.lowercase()).toByteArray(Charsets.UTF_8))
        return 1_000_000L + (BigInteger(1, seed.copyOfRange(0, 4)).toLong() and 0xFFFFFL)
    }
}
